def pxml(text):
    return escape(text, quote=False)


def module_xml(s):
    x = f'<h2>{pxml(s["title"])}</h2><callout emoji="💬"><p>{pxml(s["purpose"])}</p></callout><p>{pxml(s["contract"])}</p><ul>'
    for a in s['atoms']:
        x += f'<li><b>{a["id"]} {pxml(a["name"])}</b><ul>'
        for label, key in [('输入/输出', 'io'), ('作用', 'role'), ('边界', 'boundary')]:
            x += f'<li><b>{label}：</b>{pxml(a[key])}</li>'
        x += '</ul></li>'
    return x + '</ul>'


def md_from_xml(x):
    root = ET.fromstring('<root>' + x + '</root>')
    def conv(e):
        body = (e.text or '') + ''.join(conv(c) + (c.tail or '') for c in e)
        if e.tag in ['h2', 'h3']:
            return '\n\n' + '#' * int(e.tag[1]) + ' ' + body + '\n\n'
        if e.tag == 'b':
            return '**' + body + '**'
        if e.tag == 'p':
            return body + '\n\n'
        if e.tag in ['ol', 'ul']:
            return '\n' + body + '\n'
        if e.tag == 'li':
            return '- ' + body.replace('\n- ', '\n  - ').rstrip() + '\n'
        if e.tag == 'callout':
            return '> ' + body.strip() + '\n\n'
        return body
    return re.sub(r'\n{3,}', '\n\n', ''.join(conv(c) for c in root)).strip() + '\n'


